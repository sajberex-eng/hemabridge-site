def _sec(title, body, cls=''):
    return '''  <section class="section%s">
    <div class="wrap split">
      <div><h2>%s</h2></div>
      <div>
%s
      </div>
    </div>
  </section>
''' % (cls, title, body)

def _faq(items):
    return '''  <section class="section">
    <div class="wrap">
      <h2>Частые вопросы</h2>
      <div class="faq">
%s
      </div>
    </div>
  </section>
''' % '\n'.join('        <details><summary>%s</summary><div><p>%s</p></div></details>' % qa for qa in items)

def _cta(title, lead, btn='Получить врачебную оценку', attr=''):
    return '''  <section class="section closing">
    <div class="wrap closing-row">
      <div>
        <h2>%s</h2>
        <p class="lead">%s</p>
      </div>
      <div class="actions">
        <a class="btn btn-primary" href="#apply"%s>%s</a>
        <a class="btn btn-ghost" href="#route">Как проходит маршрут</a>
      </div>
    </div>
  </section>
''' % (title, lead, attr, btn)

